import fs from "node:fs";
let id = 0; const pending = new Map(); let ws;
const send = (method, params = {}) => {
  const i = ++id; ws.send(JSON.stringify({ id: i, method, params }));
  return new Promise((res, rej) => { pending.set(i, res); setTimeout(() => { pending.delete(i); rej(new Error("timeout")); }, 15000); });
};
const list = await (await fetch("http://127.0.0.1:9350/json/list")).json();
const page = list.find(t => t.type === "page");
ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } };
await send("Page.enable"); await send("Runtime.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 980, deviceScaleFactor: 1, mobile: false });
await send("Page.navigate", { url: "file:///D:/下载/服务器/MythicMobsStudio/app/index.html" });
await new Promise(r => setTimeout(r, 1800));
await send("Runtime.evaluate", { expression: `MM_APP.startWizard(); true` });
await new Promise(r => setTimeout(r, 1000));
const shot = await send("Page.captureScreenshot", { format: "png" });
fs.writeFileSync("docs/img/wizard.png", Buffer.from(shot.data, "base64"));
console.log("saved");
process.exit(0);
